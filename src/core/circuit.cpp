#include "core/circuit.hpp"
#include <algorithm>
#include <cmath>

namespace ana {

void Circuit::update_node_bounds(const std::vector<size_t>& connected_nodes) {
    for (size_t node : connected_nodes) {
        if (node > max_node_id) {
            max_node_id = node;
        }
    }
}

void Circuit::add_resistor(std::string id, size_t node_a, size_t node_b, double resistance) {
    auto res = std::make_unique<Resistor>(std::move(id), node_a, node_b, resistance);
    update_node_bounds(res->nodes);
    components.push_back(std::move(res));
}

void Circuit::add_voltage_source(std::string id, size_t pos_node, size_t neg_node, 
                                 double value, VoltageType type) {
    auto src = std::make_unique<VoltageSource>(std::move(id), pos_node, neg_node, value, type);
    update_node_bounds(src->nodes);
    components.push_back(std::move(src));
}

void Circuit::add_transistor(std::string id, std::string model_type, 
                             size_t t1, size_t t2, size_t t3, 
                             double w, double l, double vth) {
    auto tx = std::make_unique<Transistor>(std::move(id), std::move(model_type), t1, t2, t3, w, l, vth);
    update_node_bounds(tx->nodes);
    components.push_back(std::move(tx));
}

void Circuit::export_spice(std::ostream& os) const {
    os << "* SPICE Netlist generated by libana\n";
    os << "* Continuous-Time Physical Verification Layout\n\n";

    for (const auto& comp : components) {
        // 1. Export Resistors
        if (auto r = dynamic_cast<const Resistor*>(comp.get())) {
            os << "R" << r->name << " " << r->nodes[0] << " " << r->nodes[1] << " " << r->resistance << "\n";
        } 
        // 2. Export Voltage Sources (Natively mapping NDC to absolute negative values)
        else if (auto v = dynamic_cast<const VoltageSource*>(comp.get())) {
            double final_val = (v->type == VoltageType::NDC) ? -std::abs(v->value) : v->value;
            std::string type_str = (v->type == VoltageType::AC) ? "AC" : "DC";
            os << "V" << v->name << " " << v->nodes[0] << " " << v->nodes[1] << " " << type_str << " " << final_val << "\n";
        } 
        // 3. Export Active Transistors (BJTs/FETs)
        else if (auto tx = dynamic_cast<const Transistor*>(comp.get())) {
            // Standard SPICE notation format: Prefix with M for FETs or Q for BJTs based on your layout model
            char prefix = (tx->model == "NMOS" || tx->model == "PMOS") ? 'M' : 'Q';
            os << prefix << tx->name << " " << tx->nodes[0] << " " << tx->nodes[1] << " " << tx->nodes[2];
            
            if (prefix == 'M') {
                os << " " << tx->model << " W=" << tx->width << " L=" << tx->length << "\n";
            } else {
                os << " " << tx->model << "\n";
            }
        }
    }
    os << "\n.end\n";
}

} // namespace ana